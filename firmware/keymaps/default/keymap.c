void matrix_init_user(void) {
    gpio_set_pin_input_high(GP4);
}

static bool encoder_button_pressed = false;

void matrix_scan_user(void) {
    if (!gpio_read_pin(GP4)) { // Button pressed (active low to ground)
        if (!encoder_button_pressed) {
            tap_code(KC_MUTE); // Action when encoder button is clicked
            encoder_button_pressed = true;
        }
    } else {
        encoder_button_pressed = false;
    }
}
